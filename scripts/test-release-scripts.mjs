function createStoredOrDeflatedZip(zipPath, entries) {
  const localChunks = [];
  const centralChunks = [];
  let localOffset = 0;

  for (const entry of entries) {
    const name = Buffer.from(entry.name, "utf8");
    const data = Buffer.from(entry.data);
    const compressed = deflateRawSync(data);
    const checksum = crc32(data);

    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x0800, 6);
    local.writeUInt16LE(8, 8);
    local.writeUInt16LE(0, 10);
    local.writeUInt16LE(0, 12);
    local.writeUInt32LE(checksum, 14);
    local.writeUInt32LE(compressed.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(name.length, 26);
    local.writeUInt16LE(0, 28);
    const localRecord = Buffer.concat([local, name, compressed]);
    localChunks.push(localRecord);

    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(8, 10);
    central.writeUInt16LE(0, 12);
    central.writeUInt16LE(0, 14);
    central.writeUInt32LE(checksum, 16);
    central.writeUInt32LE(compressed.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(name.length, 28);
    central.writeUInt16LE(0, 30);
    central.writeUInt16LE(0, 32);
    central.writeUInt16LE(0, 34);
    central.writeUInt16LE(0, 36);
    central.writeUInt32LE(0, 38);
    central.writeUInt32LE(localOffset, 42);
    centralChunks.push(Buffer.concat([central, name]));

    localOffset += localRecord.length;
  }

  const centralDirectory = Buffer.concat(centralChunks);
  const eocd = Buffer.alloc(22);
  eocd.writeUInt32LE(0x06054b50, 0);
  eocd.writeUInt16LE(0, 4);
  eocd.writeUInt16LE(0, 6);
  eocd.writeUInt16LE(entries.length, 8);
  eocd.writeUInt16LE(entries.length, 10);
  eocd.writeUInt32LE(centralDirectory.length, 12);
  eocd.writeUInt32LE(localOffset, 16);
  eocd.writeUInt16LE(0, 20);

  writeFileSync(zipPath, Buffer.concat([...localChunks, centralDirectory, eocd]));
}

function createArtifactFixture(version) {
  const assetsDirectory = mkdtempSync(join(tmpdir(), "flint-assets-test-"));
  for (const platform of PLATFORMS) {
    const rawName = rawAssetName(platform.id, version);
    const rawData = Buffer.from(`raw executable for ${platform.id} ${version}\n`, "utf8");
    writeFileSync(join(assetsDirectory, rawName), rawData);
    const zipName = `${rawName.replace(/\.exe$/, "")}.zip`;
    const runningText = [
      `Flint ${version} - ${platform.id}`,
      "",
      `This archive contains ${rawName}.`,
      "Verify this archive against sha.txt before running it.",
      "",
    ].join("\n");
    createStoredOrDeflatedZip(join(assetsDirectory, zipName), [
      { name: rawName, data: rawData },
      { name: "RUNNING.txt", data: Buffer.from(runningText, "utf8") },
    ]);
  }
  return assetsDirectory;
}

